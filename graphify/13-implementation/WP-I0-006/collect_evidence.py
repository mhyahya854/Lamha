    if args.negative_probe:
        structured = probe_cases(decision)
        raw = raw_probe_cases(decision_text)
        if args.negative_probe not in structured and args.negative_probe not in raw:
            print(json.dumps({"status": "UNKNOWN_NEGATIVE_PROBE", "name": args.negative_probe}, indent=2))
            return 3
        try:
            if args.negative_probe in structured:
                candidate, expected = structured[args.negative_probe]
                validate_decision(candidate)
            else:
                candidate_text, expected = raw[args.negative_probe]
                parsed = strict_json_load_bytes(candidate_text) if isinstance(candidate_text, bytes) else strict_json_loads(candidate_text)
                validate_decision(parsed)
        except DecisionError as error:
            print(json.dumps(error.as_dict(), indent=2))
            return 2 if error.code == expected else 3
        print(json.dumps({"status": "INVALID_TEST_FAILURE", "expectedCode": expected}, indent=2))
        return 3
    if args.validate_only:
        try:
            print(json.dumps(validate_decision(decision), indent=2))
            return 0
        except DecisionError as error:
            print(json.dumps(error.as_dict(), indent=2))
            return 1
    if args.self_test:
        try:
            valid = validate_decision(decision)
        except DecisionError as error:
            print(json.dumps(error.as_dict(), indent=2))
            return 1
        probes = run_negative_probes(decision, decision_text)
        result = {"valid": valid, "negativeProbes": probes, "stateWrites": 0}
        print(json.dumps(result, indent=2))
        return 0 if all(item["result"] == "PASS" for item in probes) else 1
    return collect()


