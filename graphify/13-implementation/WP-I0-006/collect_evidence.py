def repository_fingerprint() -> dict[str, Any]:
    status = git_output("status", "--porcelain=v1", "--untracked-files=all")
    comparison = codebase_comparison()
    value = {
        "head": git_output("rev-parse", "HEAD"),
        "status": status,
        "codebaseComparison": comparison,
    }
    value["sha256"] = hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":")).encode("utf-8")).hexdigest()
    return value


