def raw_probe_cases(valid_text: str) -> dict[str, tuple[str | bytes, str]]:
    duplicate = valid_text.replace(
        '"outputExecutionAuthorized": false,',
        '"outputExecutionAuthorized": true,\n      "outputExecutionAuthorized": false,',
        1,
    )
    malformed = valid_text.rstrip()[:-1]
    nonstandard = valid_text.replace('"schemaVersion": 1', '"schemaVersion": NaN', 1)
    return {
        "raw_duplicate_authorization_key": (duplicate, "DECISION_JSON_DUPLICATE_KEY"),
        "raw_malformed_json": (malformed, "DECISION_JSON_INVALID"),
        "raw_nonstandard_constant": (nonstandard, "DECISION_JSON_NONSTANDARD_CONSTANT"),
        "raw_invalid_utf8": (b'{"schemaVersion":"\xff"}', "DECISION_JSON_INVALID"),
        "raw_excessive_nesting": ("[" * 2000 + "0" + "]" * 2000, "DECISION_JSON_INVALID"),
        "raw_oversized_integer": ("{\"schemaVersion\":" + "9" * 5000 + "}", "DECISION_JSON_INVALID"),
        "raw_oversized_document": ("{\"value\":\"" + "x" * (MAX_DECISION_BYTES + 1) + "\"}", "DECISION_JSON_INVALID"),
    }


def run_negative_probes(decision: dict[str, Any], decision_text: str) -> list[dict[str, Any]]:
    results: list[dict[str, Any]] = []
    for name, (candidate, expected_code) in probe_cases(decision).items():
        try:
            validate_decision(candidate)
            results.append({"name": name, "expectedCode": expected_code, "actualCode": None, "result": "FAIL"})
        except DecisionError as error:
            results.append({
                "name": name, "expectedCode": expected_code, "actualCode": error.code,
                "field": error.field, "result": "PASS" if error.code == expected_code else "FAIL",
            })
    for name, (candidate_text, expected_code) in raw_probe_cases(decision_text).items():
        try:
            parsed = strict_json_load_bytes(candidate_text) if isinstance(candidate_text, bytes) else strict_json_loads(candidate_text)
            validate_decision(parsed)
            results.append({"name": name, "boundary": "raw-json", "expectedCode": expected_code, "actualCode": None, "result": "FAIL"})
        except DecisionError as error:
            results.append({
                "name": name, "boundary": "raw-json", "expectedCode": expected_code,
                "actualCode": error.code, "field": error.field,
                "result": "PASS" if error.code == expected_code else "FAIL",
            })
    return results


def authority_checks() -> dict[str, Any]:
    packet_text = PACKET.read_text(encoding="utf-8")
    membership_rows = list(csv.DictReader(MEMBERSHIP.open(encoding="utf-8", newline="")))
    dependency_rows = list(csv.DictReader(DEPENDENCIES.open(encoding="utf-8", newline="")))
    packages = load_json(WORK_PACKAGES)
    test_rows = list(csv.DictReader(TEST_MATRIX.open(encoding="utf-8", newline="")))
    package = next((item for item in packages if item["work_package_id"] == PACKAGE_ID), None)
    membership = [row for row in membership_rows if row["work_package_id"] == PACKAGE_ID]
    dependencies = [row for row in dependency_rows if row["work_package_id"] == PACKAGE_ID]
    tests = [row for row in test_rows if row["work_package_id"] == PACKAGE_ID]
    prerequisite_summary = load_json(PREREQUISITE_SUMMARY)
    prerequisite_review = PREREQUISITE_REVIEW.read_text(encoding="utf-8")
    checks = {
        "packetNamesPackage": f"# {PACKAGE_ID}" in packet_text,
        "packetNamesRequirement": REQUIREMENT_ID in packet_text,
        "registryPackageMatches": bool(package and package["included_requirement_ids"] == [REQUIREMENT_ID] and package["status"] == "NOT_STARTED"),
        "membershipMatches": len(membership) == 1 and membership[0]["canonical_id"] == REQUIREMENT_ID,
        "dependencyMatches": len(dependencies) == 1 and dependencies[0]["prerequisite_work_package_id"] == "WP-I0-001",
        "testMatrixMatches": len(tests) == 1 and REQUIREMENT_ID in tests[0]["failure_cases"],
        "prerequisiteSummaryPass": prerequisite_summary.get("status") == "PASS" and not prerequisite_summary.get("failures"),
        "prerequisiteExitGatePass": all(item.get("result") == "PASS" for item in prerequisite_summary.get("exitGateClauses", [])),
        "prerequisiteCompleteAndGitHubVerified": "Final package status: COMPLETE and GitHub-verified" in prerequisite_review,
        "contractsOwned": 0,
        "schemasOwned": 0,
        "componentsOwned": 0,
    }
    checks["result"] = "PASS" if all(value is True or value == 0 for key, value in checks.items() if key != "result") else "FAIL"
    return checks


