def is_reparse(stat_result: os.stat_result, path: pathlib.Path) -> bool:
    return path.is_symlink() or bool(getattr(stat_result, "st_file_attributes", 0) & 0x400)


def recursive_inventory(base: pathlib.Path) -> dict[str, Any]:
    files: dict[str, pathlib.Path] = {}
    directories: list[str] = []
    reparses: list[str] = []
    special: list[str] = []
    stack = [base]
    while stack:
        directory = stack.pop()
        with os.scandir(directory) as entries:
            for entry in entries:
                path = pathlib.Path(entry.path)
                relative = path.relative_to(ROOT).as_posix()
                stat_result = entry.stat(follow_symlinks=False)
                if entry.is_symlink() or is_reparse(stat_result, path):
                    reparses.append(relative)
                elif entry.is_dir(follow_symlinks=False):
                    directories.append(relative)
                    stack.append(path)
                elif entry.is_file(follow_symlinks=False):
                    files[relative] = path
                else:
                    special.append(relative)
    return {
        "files": files,
        "directories": sorted(directories),
        "reparsePaths": sorted(reparses),
        "specialPaths": sorted(special),
    }


def classify_artifacts(paths: list[str]) -> dict[str, list[str]]:
    matches = {name: [] for name in ARTIFACT_SEGMENTS}
    for raw_path in sorted(set(paths)):
        segments = {segment.casefold() for segment in pathlib.PurePosixPath(raw_path.replace("\\", "/")).parts}
        for artifact_class, markers in ARTIFACT_SEGMENTS.items():
            if segments & {marker.casefold() for marker in markers}:
                matches[artifact_class].append(raw_path)
        if ".git" in segments and raw_path.replace("\\", "/").strip("/") != ".git":
            matches["repositoryCopy"].append(raw_path)
    return {name: sorted(set(class_paths)) for name, class_paths in matches.items()}


